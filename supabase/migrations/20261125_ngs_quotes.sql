-- הצעות מחיר (נ.ג.ש) – רק מי שמורשה לתמחר (גל ונסים)
create table if not exists public.ngs_quotes (
  id uuid primary key default gen_random_uuid(),
  serial_number int generated by default as identity,
  quote_date date not null default current_date,
  client_name text,
  site text,                                      -- סניף / אתר / כתובת העבודה
  subject text,                                   -- נושא ההצעה
  price_list_id uuid references public.ngs_price_lists(id) on delete set null,
  discount_pct numeric(6,2) not null default 0,   -- הנחה כללית (מוצגת ללקוח)
  terms text,                                     -- הערות ותנאים
  created_by text,
  created_at timestamptz default now(),
  updated_at timestamptz default now()
);

create table if not exists public.ngs_quote_lines (
  id uuid primary key default gen_random_uuid(),
  quote_id uuid not null references public.ngs_quotes(id) on delete cascade,
  price_item_id uuid references public.ngs_price_items(id) on delete set null,
  code text,
  description text not null,
  unit text,
  qty numeric(12,2) not null default 1,
  base_price numeric(12,2) not null default 0,
  line_pct numeric(6,2) not null default 0,       -- תוספת/הנחה שקטה (לא מוצגת ללקוח)
  sort_order int default 0,
  created_at timestamptz default now()
);
create index if not exists ngs_quote_lines_quote_idx on public.ngs_quote_lines(quote_id, sort_order);

-- הגדרות כלליות (למשל נוסח ברירת מחדל לתנאי הצעת מחיר)
create table if not exists public.ngs_settings (
  key text primary key,
  value text,
  updated_at timestamptz default now()
);

alter table public.ngs_quotes enable row level security;
alter table public.ngs_quote_lines enable row level security;
alter table public.ngs_settings enable row level security;

create policy quotes_all on public.ngs_quotes for all to authenticated using (public.app_can_price()) with check (public.app_can_price());
create policy quote_lines_all on public.ngs_quote_lines for all to authenticated using (public.app_can_price()) with check (public.app_can_price());
create policy settings_read on public.ngs_settings for select to authenticated using (public.app_is_admin());
create policy settings_write on public.ngs_settings for all to authenticated using (public.app_can_price()) with check (public.app_can_price());

